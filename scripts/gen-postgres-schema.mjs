// Writes prisma/postgres/schema.prisma from the SQLite source schema.
// Usage: npm run schema:postgres && npx prisma db push --schema prisma/postgres/schema.prisma
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const src = readFileSync("prisma/schema.prisma", "utf8");
const out = src.replace(
  /datasource db \{[^}]*\}/,
  `datasource db {\n  provider  = "postgresql"\n  url       = env("DATABASE_URL")\n  directUrl = env("DIRECT_URL")\n}`,
);
if (out === src) throw new Error("datasource block not found");
mkdirSync("prisma/postgres", { recursive: true });
writeFileSync(
  "prisma/postgres/schema.prisma",
  "// GENERATED by scripts/gen-postgres-schema.mjs. Do not edit.\n" + out,
);
console.log("wrote prisma/postgres/schema.prisma");
